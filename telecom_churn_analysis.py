y_pred_proba_lr = lr_model.predict_proba(X_test)[:,1]  # Test verisi üzerinde olasılık tahminleri

print("Confusion Matrix:\n", confusion_matrix(y_test, y_pred_lr))
print("\nClassification Report:\n", classification_report(y_test, y_pred_lr))
print(f"ROC-AUC: {roc_auc_score(y_test, y_pred_proba_lr):.2f}")

"""**Confusion Matrix (Karışıklık Matrisi)**

* Model, churn olmayanları iyi tahmin ediyor (1403/1552
= %90 doğru).

* Churn olanları tahmin etmek daha zor (283/561 = %50 doğru).

* Yani dengesiz veri etkisi var: Model sık olan sınıfa (0) daha iyi uyum sağlıyor.

**Classification Report**

* **Precision (kesinlik):** Tahmin edilen pozitiflerin ne kadarının doğru olduğu.

  * Churn için precision = 0.66 → Modelin “churn” dediği müşterilerin %66’sı gerçekten churn olmuş.

* **Recall (duyarlılık):** Gerçek pozitiflerden ne kadarını doğru tahmin etti.

  * Churn için recall = 0.50 → Gerçek churn müşterilerin sadece %50’si doğru tahmin edilmiş.

* **F1-score:** Precision ve recall’un harmonik ortalaması.

  * Churn için 0.57 → Dengeli bir başarı ölçüsü, ama düşük.

**Yorum:**

* Model, churn olan müşterileri yakalamakta zorluk çekiyor (recall düşük).

* Churn olmayan müşteriler iyi tahmin ediliyor (precision ve recall yüksek).

* Random Forest ve XGBoost modellerini de inceleyeceğiz.
"""

