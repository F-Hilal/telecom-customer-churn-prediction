X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42, stratify=y)

print("Eğitim seti boyutu:", X_train.shape)
print("Test seti boyutu:", X_test.shape)

"""* Veri, eğitim (%70) ve test (%30) setine ayrıldı; stratify=y sayesinde Churn oranı her iki sette de aynı kaldı, bu dengesiz veri için modelin doğru değerlendirilmesini sağlar.

* Veri seti toplam 7043 satır içeriyor (4930 + 2113 = 7043) ve her satır için 19 özellik bulunuyor.
"""

# Lojistik Regresyon modeli ile churn tahmin yapılması ve performans metriklerinin hesaplanması
