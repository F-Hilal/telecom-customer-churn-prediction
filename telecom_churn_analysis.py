"""**Adım 3: Model Seçimi ve Eğitimi**"""

# Modelleme için özellik (X) ve hedef (y) değişkenlerini ayırma
X = df_encoded.drop('Churn', axis=1)  # Tüm sütunlar ama Churn hariç
y = df_encoded['Churn']               # Hedef değişken

# Veriyi %70 eğitim, %30 test olarak bölüyoruz
